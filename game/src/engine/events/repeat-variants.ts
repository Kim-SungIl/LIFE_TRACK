// 가장 자주 반복되는 사건 셋의 **문장 변이**. (T60)
//
// 왜 이 셋인가 (실측, balanced 페르소나 5판 평균):
//   판당 총 발동 350건 중 **218건(62%)이 변이 1개짜리 27종**이었다. 그중 같은 문장을
//   가장 많이 보는 셋이 아래다 — fatigue-warning 13.0회 · good-grade 12.4회 ·
//   music-discovery 10.4회. 한 판에서 **같은 문장을 열 번 넘게** 읽는다.
//
// 반대로 반장 잡무 3종은 이미 학교급당 변이 4개라 같은 문장이 ~2회였다. 즉 "잡무가
// 지겹다"는 진단은 표적을 빗나갔고, 진짜 표적은 변이가 아예 없는 쪽이었다.
//
// **밸런스는 한 글자도 안 건드린다.** 변이는 text·message만 덮고 effects·fatigueEffect·
// condition은 전부 카탈로그(events 배열)에 남는다(eventPresentation.overlayChoices).
//
// 학교급은 말투와 소재로 가른다 — 초6은 집과 교실의 소박한 디테일, 중등은 학원과 친구,
// 고등은 야자·모의고사. 같은 사건이라도 그 나이에 실제로 일어날 법한 자리에 둔다.
import type { EventTextVariant, SchoolVariants } from '../types';

function variant(
  description: string,
  c0: { text: string; message: string },
  c1: { text: string; message: string },
): EventTextVariant {
  return { description, choices: [c0, c1] };
}

