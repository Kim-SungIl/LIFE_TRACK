// 친구 초대·약속의 말투 — 월 계획 화면의 초대 카드와 재생 카드의 약속 줄(📌·💔). (설계안 §6·§11 "친구별 말투")
//
// 예전엔 모든 친구가 같은 한 줄이었다("N주차 토요일에 같이 놀래?" / "알겠어… 다음에 하자."). 초대는 달마다 모양이
// 다른 외부 요청으로 4주를 "복사본"이 되지 않게 하려고 넣은 것인데(§6), 누가 불러도 같은 말이면 그 일을 못 한다.
// 그래서 친구마다 성격(npcRoster personality)·잡담(npcSmalltalk) 말투에 맞춘 줄을 둔다.
//
// 규칙
//   · 반말, 잡담과 같은 결. 학교급·학년·계절에 묶인 말은 안 쓴다 — 초대는 아무 달에나 뜬다(지훈은 초등부터, 준하는 고등만).
//   · 약속 결과 줄(kept·broken)은 **활동과 무관하게** 쓴다 — 같은 줄이 놀기(hang-out)와 공부(study-group) 약속 둘 다에 붙는다.
//   · 거절 반응(decline)은 작은 서운함까지만(친밀도 −1). 못 지킨 약속(broken)은 그보다 한 칸 무겁게(−2).
//   · `{when}`은 "2주차 토요일" 같은 그 칸의 때로 바뀐다.
//   · 문장 고르기는 결정론 — 초대 주차로 고른다(같은 초대를 다시 그려도 같은 말).
export interface InviteVoice {
  /** 놀자는 초대(hang-out). */
  readonly hangOut: readonly string[];
  /** 시험 주(와 준비 주)에 같이 공부하자는 초대(study-group). */
  readonly study: readonly string[];
  /** 거절했을 때 그 친구의 반응. 따옴표로 시작하면 "이름: " 뒤에 붙인다. */
  readonly decline: string;
  /** 약속을 지킨 주의 한 줄(📌 뒤). */
  readonly kept: string;
  /** 약속을 못 지킨 주의 한 줄(💔 뒤). */
  readonly broken: string;
}

