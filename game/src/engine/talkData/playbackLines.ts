/**
 * 그 주의 한 줄. 고를 거리가 없으면 null(카드는 결산 대사로 넘어간다).
 *   ① 이번 주로 새 단계에 닿은 루틴 — 그 주는 루틴의 주다
 *   ② 주말·방학 활동 — 주마다 달라지는 쪽이라 먼저 본다(루틴은 한 달 내내 같다)
 *   ③ 루틴의 지금 단계
 */
export function playbackLine(log: Pick<WeekLog, 'played' | 'year' | 'week'>): string | null {
  const played = log.played;
  if (!played) return null;
  const week = log.week ?? 0;
  const year = log.year ?? 0;
  const routineLine = (r: { id: string; stage: number }) => {
    const stages = ROUTINE_LINES[r.id];
    if (!stages) return null;
    return stages[Math.min(Math.max(r.stage, 0), ROUTINE_STAGES - 1)][(week + year) % 2];
  };
  for (const r of played.routines) {
    if (r.reached) { const line = routineLine(r); if (line) return line; }
  }
  // 같은 활동이 칸 여럿을 채워도 한 번으로 센다 — 휴식 두 칸이 도서관 몰입 한 칸보다 두 배 자주 뽑히면 그 주의 무게가 거꾸로다.
  const choices = [...new Set(played.choices)].filter(id => CHOICE_LINES[id]);
  if (choices.length > 0) {
    // 활동 고르기와 변이 고르기를 같은 `week % n`에 묶으면 n=2일 때 A는 늘 변이 0, B는 늘 변이 1이 된다(모듈로 축 퇴화).
    const id = choices[week % choices.length];
    return CHOICE_LINES[id][(Math.floor(week / choices.length) + year) % 2];
  }
  for (const r of played.routines) {
    const line = routineLine(r);
    if (line) return line;
  }
  return null;
}

/**
 * 재생 카드의 머리 줄(사건 📖이 없는 주) — 시험·마일스톤 독백 > 그 주에 실제로 한 루틴·활동의 한 줄 > 결산 독백.
 * 번아웃 주는 결산 독백이 맞다(무엇을 했는지보다 무너진 게 그 주다).
 */
export function cardLine(state: GameState, weekLog: WeekLog, resultDialogue: string): string {
  if (state.mentalState === 'burnout' || isStrongResultWeek(state, weekLog)) return resultDialogue;
  return playbackLine(weekLog) ?? resultDialogue;
}
