/**
 * 그 주의 한 줄. 고를 거리가 없으면 null(카드는 결산 대사로 넘어간다).
 *   ① 이번 주로 새 단계에 닿은 루틴 — 그 주는 루틴의 주다
 *   ② 주말·방학 활동 — 주마다 달라지는 쪽이라 먼저 본다(루틴은 한 달 내내 같다)
 *   ③ 루틴의 지금 단계
 */
export function playbackLine(log: Pick<WeekLog, 'played' | 'year' | 'week'>): string | null {
  const played = log.played;
  if (!played) return null;
  // 판 전체의 절대 주 — 학년이 바뀌어도 이어서 센다. 변이 수가 활동마다 달라도(2~8) 한 축으로 돈다.
  const abs = Math.max(0, absWeek(log.year ?? 1, log.week ?? 0));
  const routineLine = (r: { id: string; stage: number }) => {
    const stages = ROUTINE_LINES[r.id];
    if (!stages) return null;
    const lines = stages[Math.min(Math.max(r.stage, 0), ROUTINE_STAGES - 1)];
    return lines[abs % lines.length];
  };
  for (const r of played.routines) {
    if (r.reached) { const line = routineLine(r); if (line) return line; }
  }
  // 같은 활동이 칸 여럿을 채워도 한 번으로 센다 — 휴식 두 칸이 도서관 몰입 한 칸보다 두 배 자주 뽑히면 그 주의 무게가 거꾸로다.
  const choices = [...new Set(played.choices)].filter(id => CHOICE_LINES[id]);
  if (choices.length > 0) {
    // 활동 고르기와 변이 고르기를 같은 `abs % n`에 묶으면 n=2일 때 A는 늘 변이 0, B는 늘 변이 1이 된다(모듈로 축 퇴화).
    // 그래서 변이는 몫(⌊abs / n⌋)으로 고른다 — 같은 활동 n개를 이어서 하면 그 활동이 나올 때마다 몫이 1씩 늘어
    // 변이 수와 n이 무엇이든 모든 변이를 차례로 돈다.
    const id = choices[abs % choices.length];
    const lines = CHOICE_LINES[id];
    return lines[Math.floor(abs / choices.length) % lines.length];
  }
  for (const r of played.routines) {
    const line = routineLine(r);
    if (line) return line;
  }
  return null;
}

/**
 * 재생 카드의 머리 줄 — 결과 화면을 건너뛴 사건 문장 > 시험·마일스톤 독백 > 그 주에 실제로 한 루틴·활동의 한 줄 > 결산 독백.
 * 번아웃 주는 결산 독백이 맞다(무엇을 했는지보다 무너진 게 그 주다).
 *
 * 사건 문장은 결과 화면에서 방금 읽었다 — 결과 화면을 건너뛴 가벼운 사건(`weekLog.lightNarration`, light-result.ts)만
 * 다시 올린다. 나머지 사건 주도 그 주에 한 일을 쓴다: 배지가 주 전체 순변화라 머리 줄도 주 전체 이야기여야 서로 맞는다
 * (사건 문장을 올리면 결과 화면의 "멘탈 +0.4" 칩 옆에 주 전체 "멘탈 ▼"가 놓여 모순처럼 읽혔다).
 */
export function cardLine(state: GameState, weekLog: WeekLog, resultDialogue: string): string {
  const lastNarration = weekLog.messages.filter(m => m.startsWith('📖')).at(-1);
  if (lastNarration && lastNarration === weekLog.lightNarration) return lastNarration.replace(/^📖\s*/, '');
  if (state.mentalState === 'burnout' || isStrongResultWeek(state, weekLog)) return resultDialogue;
  return playbackLine(weekLog) ?? resultDialogue;
}
