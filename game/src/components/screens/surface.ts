// 사진 위에 UI를 얹을 때의 공용 값. **BgWrapper에서 분리했다** —
// 컴포넌트 파일이 함수까지 내보내면 react-refresh/only-export-components가 막는다.
// 배경 사진의 불투명도. **0.25였다** — 같은 교실 그림이 이벤트 장면(EventScene은 1.0)에선
// 무대였는데 주간 화면에선 희미한 텍스처였다. 플레이 시간의 대부분이 이 화면인데 그림이
// 4배 옅게 깔려 있었고, 그래서 "게임"이 아니라 "앱"으로 읽혔다.
//
// 올려도 글자가 안 죽는 이유: 이 래퍼 안의 카드는 전부 rgba(42,34,48,0.85)+blur(6px)로
// 자기 바닥을 갖는다(StatsPanel·ExamTimeline·독백 말풍선). 카드 밖에 맨몸으로 있던 둘
// (HUD·자동저장 표시)은 같은 유리 바닥을 받았다 — 배경을 올리는 일과 한 쌍이다.
//
// 최종 값은 **게임에서 눈으로 보고 정할 것**. 화면마다 다르게 하려면 bgOpacity로 넘긴다.
export const BG_IMAGE_OPACITY = 0.55;

// 아직 손보지 않은 화면이 쓰는 값. 사진을 올리는 일은 **그 화면의 맨몸 요소에 바닥을 까는 일과
// 한 쌍**이라, 짝을 안 맞춘 화면에 사진만 올리면 대비가 내려간다.
// 학년말·엔딩은 맨몸 요소가 각각 3·34개라 이번 범위 밖이고, 그래서 옛 값을 유지한다.
// (실측: 0.25→0.55에서 엔딩 AA 미달 21→24건, 학년말 1→2건)
export const BG_IMAGE_OPACITY_UNTREATED = 0.25;

/** 사진 위에 놓이는 카드의 표준 바닥. StatsPanel·ExamTimeline·독백이 이미 쓰던 값이다. */
export const GLASS_BASE = 'rgba(42,34,48,0.85)';

/**
 * 색조 패널을 사진 위에 놓을 때 쓴다 — **색조는 그대로 두고 불투명 바닥만 깐다.**
 * `rgba(224,138,91,0.15)` 같은 값은 색을 입힐 뿐 바닥이 아니라서, 사진이 진해지면
 * 그 위 글자가 먼저 죽는다(실측: 다가오는 이벤트 배너 2.67:1 → 1.60:1).
 */
export function tintedGlass(tint: string): string {
  return `linear-gradient(${tint}, ${tint}), ${GLASS_BASE}`;
}
