// CG 자산 manifest 생성기
// public/images/events/ 아래에 실제로 존재하는 .png 파일 목록을 스캔해서
// src/cg-manifest.generated.ts 로 export.
//
// GameScreen.tsx의 CG cascade가 자산 부재 케이스에서 8개 후보를 직렬 404로
// 두드리는 비용을 없애기 위함. manifest lookup으로 hasCg를 즉시 결정.
//
// 실행: cd game && node scripts/generate-cg-manifest.mjs
// 자동 실행: package.json의 predev / prebuild 훅

import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isAssetFile } from './lib/asset-filter.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const EVENTS_DIR = join(ROOT, 'public/images/events');
const OUT_PATH = join(ROOT, 'src/cg-manifest.generated.ts');
const CHARACTERS_DIR = join(ROOT, 'public/images/characters');
const CHAR_OUT_PATH = join(ROOT, 'src/character-manifest.generated.ts');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    // 백업/리뷰 디렉토리 제외 (_archive, _review 등 underscore prefix)
    if (name.startsWith('_')) continue;   // 규칙 SSOT: lib/asset-filter.mjs
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      out.push(...walk(full));
    } else if (name.endsWith('.png')) {
      out.push(relative(EVENTS_DIR, full).replace(/\\/g, '/'));
    }
  }
  return out;
}

if (!existsSync(EVENTS_DIR)) {
  console.warn(`[cg-manifest] events dir not found, writing empty manifest: ${EVENTS_DIR}`);
}

const files = existsSync(EVENTS_DIR) ? walk(EVENTS_DIR).sort() : [];

const content = `// Auto-generated by scripts/generate-cg-manifest.mjs — do not edit.
// Lists every CG file present under public/images/events/ at build time.
// Used by GameScreen to skip non-existent CG candidates without 404 round-trips.
export const CG_MANIFEST: ReadonlySet<string> = new Set([
${files.map(f => `  '${f}',`).join('\n')}
]);
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, content);
console.log(`[cg-manifest] ${files.length} files indexed → ${relative(ROOT, OUT_PATH)}`);


// ===== 캐릭터 자산 manifest =====
// CG와 **같은 이유**로 필요하다. 초상/스프라이트도 존재하지 않는 후보를 먼저 두드린다:
//   · HUD 초상은 멘탈로 표정을 고르는데(mentalToExpression) happy/sad/tired/burnout 실물이 0장이라
//     멘탈이 바뀔 때마다 없는 파일을 요청하고 실패한 뒤 neutral로 되돌아온다.
//     (dev에선 SPA 폴백이 200 text/html 1,278B를 주고 디코드가 깨진다. 배포에선 진짜 404다.)
//   · EventScene은 여주 플레이에서 `{id}_{stage}_fullbody_f.png`를 먼저 본다 —
//     28장 중 실물은 jihun_elementary 하나뿐이라 **NPC 스프라이트마다 헛 왕복 1회**다.
// 표정 실물이 들어오면 이 manifest가 자동으로 잡아서 코드 수정 없이 켜진다.
const charFiles = existsSync(CHARACTERS_DIR)
  ? readdirSync(CHARACTERS_DIR).filter(isAssetFile).sort()
  : [];

writeFileSync(CHAR_OUT_PATH, `// Auto-generated by scripts/generate-cg-manifest.mjs — do not edit.
// public/images/characters/ 에 build 시점에 실재하는 파일 목록.
// Portrait / EventScene 이 없는 후보를 요청하지 않도록 쓴다.
export const CHARACTER_MANIFEST: ReadonlySet<string> = new Set([
${charFiles.map(f => `  '${f}',`).join('\n')}
]);
`);
console.log(`[char-manifest] ${charFiles.length} files indexed → ${relative(ROOT, CHAR_OUT_PATH)}`);
