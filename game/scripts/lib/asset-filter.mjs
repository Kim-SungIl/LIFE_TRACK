// 자산 스캔 규칙 — 생성기와 테스트가 **같은 함수**를 쓴다.
//
// 규칙을 생성기 안에 인라인으로 두면 잠글 수가 없다. `_archive`는 디렉토리라
// 비재귀 readdir + `.png` 필터에 이미 걸리고, 최상위에 `_` 접두 png가 0건이라
// **필터를 지워도 결과가 같다** — corpus가 0이면 게이트가 자기 삭제를 못 잡는다(#437).
// 그래서 규칙을 꺼내 합성 입력으로 직접 검사한다.

/** 매니페스트에 넣을 파일인가. `_` 접두(백업·작업본)와 png 아닌 것을 뺀다. */
export function isAssetFile(name) {
  return !name.startsWith('_') && name.endsWith('.png');
}
